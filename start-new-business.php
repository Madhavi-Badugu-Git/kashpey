    <script>
    (function() {
        const canvas = document.getElementById('mt-particles');
        if (!canvas) return;
        const ctx = canvas.getContext('2d');
        let W, H;
        const COLORS = ['#23adeb', '#fed109', '#64ba4d', '#ffffff', '#003b66', '#87ceeb'];
        const COUNT = 65;
        const particles = [];

        function resize() {
            W = canvas.width = window.innerWidth;
            H = canvas.height = window.innerHeight;
        }
        resize();
        window.addEventListener('resize', resize, {
            passive: true
        });

        function rand(a, b) {
            return a + Math.random() * (b - a);
        }
        class Particle {
            constructor() {
                this.reset(true);
            }
            reset(init) {
                this.x = rand(0, W);
                this.y = init ? rand(0, H) : H + 10;
                this.r = rand(0.6, 2.8);
                this.alpha = 0;
                this.maxA = rand(0.3, 0.85);
                this.speed = rand(0.003, 0.01);
                this.dir = 1;
                this.color = COLORS[Math.floor(Math.random() * COLORS.length)];
                this.vx = rand(-0.12, 0.12);
                this.vy = rand(-0.3, -0.08);
                this.phase = rand(0, Math.PI * 2);
                this.type = Math.random() > 0.5 ? 'star' : 'circle';
            }
            draw(t) {
                const flicker = 0.5 + 0.5 * Math.sin(t * 0.003 + this.phase);
                ctx.save();
                ctx.globalAlpha = this.alpha * flicker;
                ctx.fillStyle = this.color;
                ctx.shadowBlur = this.r * 10;
                ctx.shadowColor = this.color;
                if (this.type === 'star') {
                    const r = this.r;
                    ctx.beginPath();
                    for (let i = 0; i < 8; i++) {
                        let ang = (i * Math.PI) / 4,
                            len = i % 2 === 0 ? r * 3 : r;
                        let px = this.x + Math.cos(ang) * len,
                            py = this.y + Math.sin(ang) * len;
                        i === 0 ? ctx.moveTo(px, py) : ctx.lineTo(px, py);
                    }
                    ctx.closePath();
                    ctx.fill();
                } else {
                    ctx.beginPath();
                    ctx.arc(this.x, this.y, this.r, 0, Math.PI * 2);
                    ctx.fill();
                }
                ctx.restore();
            }
            update() {
                this.alpha += this.speed * this.dir;
                if (this.alpha >= this.maxA) this.dir = -1;
                if (this.alpha <= 0) {
                    this.reset(false);
                    return;
                }
                this.x += this.vx;
                this.y += this.vy;
                if (this.x < -10) this.x = W + 10;
                if (this.x > W + 10) this.x = -10;
                if (this.y < -10) this.reset(false);
            }
        }
        for (let i = 0; i < COUNT; i++) particles.push(new Particle());
        let t = 0;

        function loop() {
            ctx.clearRect(0, 0, W, H);
            t++;
            particles.forEach(p => {
                p.update();
                p.draw(t);
            });
            requestAnimationFrame(loop);
        }
        loop();
    })();

    (function() {
        const els = document.querySelectorAll('[data-reveal]');
        const obs = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    const el = entry.target;
                    const delay = parseInt(el.getAttribute('data-delay') || 0);
                    setTimeout(() => el.classList.add('revealed'), delay);
                    obs.unobserve(el);
                }
            });
        }, {
            threshold: 0.12,
            rootMargin: '0px 0px -40px 0px'
        });
        els.forEach(el => obs.observe(el));
    })();
    </script>

